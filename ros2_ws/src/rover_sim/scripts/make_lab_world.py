#!/usr/bin/env python3
"""Regenerate the MISSION X laboratory world and its Nav2 map.

Writes
  rover_sim/worlds/lab.pgm         tall furniture (benches, cupboard, pillar)
  rover_sim/worlds/lab.yaml        rover_core.sim world file: the PGM + boxes /
                                   cylinders with heights (chairs, LOW crates)
  rover_navigation/maps/lab.{pgm,yaml}
                                   map_server map of what the 0.62 m LiDAR can
                                   see, in the ``map`` frame (= start pose, like
                                   a slam_toolbox map)

Usage (from ros2_ws/src):
  PYTHONPATH=rover_core python3 rover_sim/scripts/make_lab_world.py
"""
from __future__ import annotations

import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(SRC, "rover_core"))

from rover_core.params import DEFAULT  # noqa: E402
from rover_core.sim import Box, Cylinder, World  # noqa: E402

SIZE = (10.0, 7.0)
START = (1.3, 1.9, 0.0)          # x, y [m], yaw [deg]; clear of furniture
PGM_RES = 0.05
FURNITURE_HEIGHT = 0.90          # everything in lab.pgm (all above the LiDAR plane)

# tall furniture -> lab.pgm  (x, y, sx, sy, yaw_deg)
TALL_BOXES = [
    ("bench_north", 5.0, 6.55, 8.6, 0.7, 0.0),
    ("bench_east", 9.55, 3.6, 0.7, 4.2, 0.0),
    ("bench_south", 3.2, 0.45, 3.4, 0.7, 0.0),
    ("island", 5.2, 3.6, 2.6, 0.9, 0.0),
    ("cupboard", 0.45, 4.6, 0.7, 1.4, 0.0),
]
TALL_CYLINDERS = [("pillar", 7.6, 1.6, 0.18)]
# chairs: 0.45 m seat (below the LiDAR plane) + thin 0.85 m backrest
CHAIRS = [(2.6, 5.5, 180), (3.6, 5.6, 170), (6.6, 5.5, 190), (5.2, 2.55, 0), (4.0, 4.65, 180),
          (8.6, 4.4, 270)]
# LOW obstacles invisible to the mast LiDAR: (name, x, y, sx, sy, yaw, height)
CRATES = [("crate0", 3.0, 2.6, 0.40, 0.30, 15.0, 0.20),
          ("crate1", 6.9, 3.0, 0.35, 0.35, 40.0, 0.28),
          ("crate2", 8.0, 5.4, 0.45, 0.30, -10.0, 0.16),
          ("crate3", 2.2, 3.7, 0.30, 0.30, 0.0, 0.25)]
ROCKS = [("rock0", 6.0, 1.5, 0.15, 0.12)]


def write_pgm(path: str, occupied: np.ndarray) -> None:
    """occupied[row=y (bottom first), col=x] -> P5 PGM (0 = occupied, 254 = free)."""
    img = np.where(occupied, 0, 254).astype(np.uint8)[::-1, :]
    with open(path, "wb") as f:
        f.write(f"P5\n{img.shape[1]} {img.shape[0]}\n255\n".encode())
        f.write(img.tobytes())


def furniture_grid() -> np.ndarray:
    w = World(size=SIZE, resolution=0.01, name="furniture")
    for name, x, y, sx, sy, yaw in TALL_BOXES:
        w.add_box(Box(x, y, sx, sy, yaw, FURNITURE_HEIGHT, name))
    for name, x, y, r in TALL_CYLINDERS:
        w.add_cylinder(Cylinder(x, y, r, FURNITURE_HEIGHT, name))
    grid, _, _ = w.to_occupancy(0.0, PGM_RES)
    return grid > 0


def chair_boxes():
    out = []
    for i, (cx, cy, yaw) in enumerate(CHAIRS):
        out.append((f"chair{i}_seat", cx, cy, 0.42, 0.42, float(yaw), 0.45))
        c, s = np.cos(np.radians(yaw)), np.sin(np.radians(yaw))
        out.append((f"chair{i}_back", round(cx - 0.20 * c, 3), round(cy - 0.20 * s, 3), 0.04, 0.42,
                    float(yaw), 0.85))
    return out


def world_yaml() -> str:
    lines = [
        "# MISSION X laboratory (~10 m x 7 m) for rover_sim / rover_core.sim.",
        "# Generated by rover_sim/scripts/make_lab_world.py - edit the script, not this file.",
        "#",
        "# Heights matter: the LDS-01 scans a plane at ~0.62 m, the HC-SR04 ultrasonic",
        "# sensors sit at ~0.25 m. lab.pgm holds the tall furniture (benches, cupboard,",
        f"# pillar; stamped at {FURNITURE_HEIGHT} m). Chairs (0.45 m seat + thin 0.85 m",
        "# backrest) and the LOW crates / rock (0.12-0.28 m) are listed below with their",
        "# heights: the LiDAR cannot see them, the ultrasonic costmap layer can.",
        "name: lab",
        f"size: [{SIZE[0]}, {SIZE[1]}]",
        "resolution: 0.02",
        "origin: [0.0, 0.0]",
        f"start: [{START[0]}, {START[1]}, {START[2]}]   # x [m], y [m], yaw [deg]",
        "image: lab.pgm",
        f"image_resolution: {PGM_RES}",
        "image_origin: [0.0, 0.0]",
        f"image_height: {FURNITURE_HEIGHT}",
        "outer_walls: true",
        "wall_thickness: 0.1",
        "wall_height: 2.0",
        "boxes:",
    ]
    for name, x, y, sx, sy, yaw, h in chair_boxes() + CRATES:
        lines.append(f"  - {{name: {name}, x: {x}, y: {y}, sx: {sx}, sy: {sy}, yaw: {yaw}, height: {h}}}")
    lines.append("cylinders:")
    for name, x, y, r, h in ROCKS:
        lines.append(f"  - {{name: {name}, x: {x}, y: {y}, r: {r}, height: {h}}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--worlds-dir", default=os.path.join(SRC, "rover_sim", "worlds"))
    ap.add_argument("--maps-dir", default=os.path.join(SRC, "rover_navigation", "maps"))
    args = ap.parse_args()
    os.makedirs(args.worlds_dir, exist_ok=True)
    os.makedirs(args.maps_dir, exist_ok=True)

    write_pgm(os.path.join(args.worlds_dir, "lab.pgm"), furniture_grid())
    yaml_path = os.path.join(args.worlds_dir, "lab.yaml")
    with open(yaml_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(world_yaml())

    world = World.from_yaml(yaml_path)
    # what the LiDAR sees (obstacles reaching its scan plane), map frame = start pose
    lidar_min = DEFAULT.lidar_height - 0.02
    grid, res, origin = world.to_occupancy(lidar_min, PGM_RES)
    write_pgm(os.path.join(args.maps_dir, "lab.pgm"), grid > 0)
    sx, sy = START[0], START[1]
    with open(os.path.join(args.maps_dir, "lab.yaml"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# LiDAR-visible map of rover_sim/worlds/lab.yaml (obstacles >= "
                f"{lidar_min:.2f} m), generated by\n# rover_sim/scripts/make_lab_world.py. "
                "Frame: map = rover start pose (like a slam_toolbox map),\n# so AMCL starts at "
                "(0, 0, 0). Crates and chair seats are NOT in this map.\n")
        f.write(f"image: lab.pgm\nmode: trinary\nresolution: {res}\n"
                f"origin: [{origin[0] - sx:.3f}, {origin[1] - sy:.3f}, 0.0]\n"
                "negate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n")
    low = int(((world.height > 0) & (world.height < lidar_min)).sum())
    print(f"wrote {yaml_path} ({world.nx}x{world.ny} cells, {low} low-obstacle cells) and "
          f"{os.path.join(args.maps_dir, 'lab.yaml')} ({grid.shape[1]}x{grid.shape[0]} @ {res} m)")


if __name__ == "__main__":
    main()
