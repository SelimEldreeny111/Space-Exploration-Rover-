#!/usr/bin/env python3
"""Bundle the web ground station's ES modules into one classic script.

Chrome and Edge refuse to load ES modules from ``file://`` URLs, so a
double-clicked ``web/index.html`` loads ``web/js/gs-bundle.js`` instead (served
over http(s) the page uses the modules directly). This script generates that
bundle; it is *not* needed to run anything -- the generated file is kept in the
repository and ``python/tests/test_generated_files.py`` fails if it is stale.

Each module is wrapped in a function scope; ``import {a, b as c} from './x.js'``
becomes ``const {a, b: c} = __mx.x`` and ``export`` declarations are collected
into the module's return object. Only the subset of module syntax used by the
ground station is supported (named imports/exports, no default exports, no
``export {...}`` lists) -- anything else is rejected loudly.

    python tools/bundle_web.py           # rewrite web/js/gs-bundle.js
    python tools/bundle_web.py --check   # exit 1 if it is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

WEB = Path(__file__).resolve().parents[1] / "web"
JS = WEB / "js"
OUT = JS / "gs-bundle.js"
#: dependency order (each module only imports from modules listed before it)
MODULES = ["ssp", "protocol", "sim", "gs", "serial", "widgets", "app"]

IMPORT_RE = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'\./([\w-]+)\.js';[ \t]*$", re.M | re.S)
IMPORT_NS_RE = re.compile(r"^import\s*\*\s*as\s+(\w+)\s+from\s*'\./([\w-]+)\.js';[ \t]*$", re.M)
EXPORT_RE = re.compile(r"^export\s+(?:(async)\s+)?(function\*?|class|const|let)\s+([A-Za-z_$][\w$]*)", re.M)


def transform(name: str, src: str, exports: dict[str, set[str]]) -> tuple[str, list[str]]:
    def imp(m: re.Match) -> str:
        mod = m.group(2)
        if mod not in exports:
            raise SystemExit(f"{name}.js imports ./{mod}.js before it is bundled (fix MODULES order)")
        parts = []
        for item in (p.strip() for p in m.group(1).split(",")):
            if not item:
                continue
            src_name, _, alias = (s.strip() for s in item.partition(" as "))
            if src_name not in exports[mod]:
                raise SystemExit(f"{name}.js imports '{src_name}' which ./{mod}.js does not export")
            parts.append(f"{src_name}: {alias}" if alias else src_name)
        return f"const {{ {', '.join(parts)} }} = __mx.{mod};"

    src = IMPORT_RE.sub(imp, src)
    src = IMPORT_NS_RE.sub(lambda m: f"const {m.group(1)} = __mx.{m.group(2)};", src)
    if re.search(r"^\s*(import|export)\s*(\{|\*|default)", src, re.M):
        raise SystemExit(f"{name}.js uses module syntax the bundler does not support")
    names = [m.group(3) for m in EXPORT_RE.finditer(src)]
    src = EXPORT_RE.sub(lambda m: m.group(0)[len("export "):].lstrip(), src)
    if re.search(r"^export\b", src, re.M):
        raise SystemExit(f"{name}.js: unsupported export statement")
    return src, names


def build() -> str:
    exports: dict[str, set[str]] = {}
    out = ["// GENERATED by ground_station/tools/bundle_web.py from web/js/*.js -- DO NOT EDIT.",
           "// Classic-script build of the ES modules for pages opened from file:// (Chrome/Edge",
           "// block ES modules there). Regenerate after changing any module.",
           "(function () {",
           "'use strict';",
           "const __mx = {};"]
    for name in MODULES:
        src = (JS / f"{name}.js").read_text(encoding="utf-8")
        body, names = transform(name, src, exports)
        exports[name] = set(names)
        out.append(f"\n// ---- {name}.js " + "-" * max(0, 66 - len(name)))
        out.append(f"__mx.{name} = (function () {{")
        out.append(body.rstrip("\n"))
        out.append(f"return {{ {', '.join(names)} }};" if names else "return {};")
        out.append("})();")
    out.append("})();")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run tools/bundle_web.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text) // 1024} KiB, {len(MODULES)} modules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
